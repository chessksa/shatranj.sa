import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(p,'utf8');
const home=read('index.html');
const tune=read('v2/home/desktop-board-shell-tune.mjs');
const play=read('v2/home/inline-play.mjs');
const computer=read('v2/home/inline-computer.mjs');
const notebook=read('v2/home/move-notebook.mjs');
const style=read('v2/home/move-notebook.css');
const mobile=read('mobile-home-fixed-v1.js');

assert.match(home,/data-move-notebook href="v2\/home\/move-notebook\.css\?v=/,'Notebook styling must load on desktop');
assert.equal(tune.match(/await import\(`\.\/inline-play\.mjs\?v=\$\{tuneAssetVersion\}`\)/g)?.length,1,'Online play controller must load exactly once');
assert.match(notebook,/document\.body\.appendChild\(root\)/,'Move table must mount outside the board grid');
assert.doesNotMatch(style,/desktop-move-notebook-active \.desktop-board-stage/,'Notation cannot override board layout');
assert.match(style,/\.move-notebook-columns,\.move-notebook-row\{display:grid/,'The move table uses a 3-column grid');
assert.doesNotMatch(style,/calc\(100vw[^\n]*chess-notebook-width/,'Move notebook must not subtract width from the board');
assert.match(style,/position:fixed/,'Left-side notation must use viewport coordinates without moving the board');
assert.doesNotMatch(style,/data-mode="docked"|data-mode="compact"/,'Collapsed UI rules must be removed');
assert.doesNotMatch(notebook,/root\.dataset\.mode|root\.dataset\.open/,'Notation must never auto-collapse');
assert.match(notebook,/const availableLeft=Math\.max\(0,Math\.floor\(rect\.left-edge-gap\)\)/,'Measure actual free viewport space');
assert.doesNotMatch(style,/transform:translateX\(calc\(var\(--chess-notebook-width\)/,'The live board must never be translated when the notebook appears');
assert.match(notebook,/const width=Math\.min\(680,availableLeft\)/,'Never enlarge the notation beyond the real space left of the board');
assert.match(style,/\-\-chess-notebook-width/);
assert.match(play,/getGameMoves,/,'Online history must come from persisted match moves');
assert.match(play,/await refreshMoveNotebook\(\)/,'Online history must refresh alongside every position');
assert.match(play,/openMoveNotebook\('online'\)/);
assert.match(play,/closeMoveNotebook\('online'\)/);
assert.match(computer,/updateMoveNotebook\('computer',moveHistory\.map\(uci=>\(\{uci\}\)\)/,'Computer moves must be captured as played');
assert.match(computer,/\{finished:true\}/,'Computer review starts at game finish');
assert.match(notebook,/new StockfishAnalyzer\(\)/,'Review uses the existing local Stockfish engine');
assert.match(notebook,/scoreToCp\(evals\[i\]\)/,'Review compares evaluations before and after moves');
assert.match(notebook,/async function enrichComputerMoves/,'SAN notation is resolved from legal computer moves');
assert.match(notebook,/if\(uci\[4\]\)options\.promotion=uci\[4\]/,'Promotion must only be specified when actually played');
assert.match(notebook,/if\(expected===token&&owner==='computer'&&records\.length===originalLength\)/,'Async notation must not erase newer moves');
assert.match(notebook,/target\.replaceChildren\(grid\)/,'Idle board must be restored from the same approved PNG renderer');
assert.match(notebook,/function decorateBoardCoordinate/,'Coordinate decorators must exist');
assert.match(play,/decorateBoardCoordinate\(square,displayIndex,squareName\)/);
assert.match(computer,/decorateBoardCoordinate\(square,displayIndex,squareName\)/);
assert.match(mobile,/mfw-coordinate-rank/,'Mobile board coordinates are included');
console.log('Desktop move log, Stockfish postgame analysis and board coordinates: PASS');
